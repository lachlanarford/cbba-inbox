export default function MobileBottomNav({ user: _user }: Props) {
  const pathname = usePathname()

  function isActive(href: string) {
    if (href === '/inbox') return pathname === '/inbox' || pathname.startsWith('/inbox/')
    if (href === '/settings') return pathname === '/settings' || (pathname.startsWith('/settings') && pathname !== '/settings/knowledge' && pathname !== '/settings/canned' && pathname !== '/settings/bugs' && pathname !== '/settings/channels' && pathname !== '/settings/admin')
    return pathname === href || pathname.startsWith(`${href}/`)
  }

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-50 md:hidden bg-cbba-navy-dark border-t border-white/10">
      <div className="flex items-stretch pb-4">
        {NAV.map(({ label, href, icon }) => {
          const active = isActive(href)
          return (
            <Link
              key={href}
              href={href}
              className={`flex-1 flex flex-col items-center gap-1 py-2.5 text-[10px] font-medium active:scale-[0.97] transition-[color,transform] duration-150 ease-out ${
                active ? 'text-cbba-purple' : 'text-gray-500'
              }`}
            >
              {icon}
              <span>{label}</span>
            </Link>
          )
        })}
      </div>
    </nav>
  )
}
